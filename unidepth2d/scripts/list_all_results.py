"""Dump EVERY saved result (results_bench / results_finetune / results_tta) into one markdown file.

  python -m scripts.list_all_results     -> writes docs/ALL_RESULTS.md

Per dataset: one row per model, read from the per-run JSON aggregates ('depth' block).
Columns: d1 / AbsRel / RMSE (raw metric), d1_si (median-scaled), d1_ssi (LS scale+shift),
d1_lsl (log-LS scale; only for runs after it was added), boundary F1 (IBims only).
Aligned columns use GT -> diagnostics only.
"""
from __future__ import annotations

import glob
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DIRS = ["results_bench", "results_finetune", "results_tta", "results_bf1v2"]
DATASETS = [("ibims", "IBims-1 (zero-shot, n=100)"), ("nyu-filled", "NYU-v2 654 filled (partly in-domain)"),
            ("sun-raw", "SUN RGB-D raw (partly in-domain)"), ("diode", "DIODE val/indoors (zero-shot, n=325)"),
            ("eth3d", "ETH3D indoor DSLR, 1/4 res (zero-shot, n=219)")]
PARAMS = {"v2-l": 354, "v2-b": 97, "v2-s": 34, "moge2-l": 326, "moge2-b": 104, "moge2-s": 35, "yolo26n": 6.36,
          "S16_prox": 15.5, "S21_scale2": 15.5, "S10_ultra_L": 15.5, "S15_anch_icd": 15.5, "S18_zsclean": 15.5,
          "S19_sced": 15.5, "b1_mix": 5.1, "b10_": 5.12, "b20core": 5.18, "b20dws": 5.04, "b20_": 5.04}


def params(model):
    m = model.replace("student-", "").split("+")[0]
    for k, v in PARAMS.items():
        if m == k or m.startswith(k):
            return f"{v:g}"
    return ""


def f(v, pct=False):
    if v in (None, ""):
        return "—"
    return f"{100 * float(v):.1f}" if pct else f"{float(v):.3f}"


def main():
    out = ["# All results (auto-generated by scripts/list_all_results.py)", "",
           "d1 / d1_si / d1_ssi / d1_lsl / bF1 in %, AbsRel unitless, RMSE in m. "
           "d1_si = median-ratio scale (official SI), d1_ssi = LS scale+shift, d1_lsl = log-LS scale. "
           "Aligned columns use GT: diagnostics only. Params in M ('' = not recorded).", ""]
    for key, title in DATASETS:
        rows = []
        for d in DIRS:
            for p in sorted(glob.glob(os.path.join(ROOT, d, f"{key}__*.json"))):
                try:
                    j = json.load(open(p, encoding="utf-8"))
                    m = j["depth"]
                except (KeyError, ValueError):
                    continue
                model = j.get("model") or os.path.basename(p)[len(key) + 2:-5]
                tag = os.path.basename(p)[len(key) + 2:-5]
                bf = j.get("boundary_f1")
                if isinstance(bf, dict):
                    bf = bf.get("f1") or bf.get("F1")
                rows.append((d, tag, model, j.get("num_images"), m, bf))
        out += [f"## {title}", "",
                "| Source | Model (file tag) | Params | n | d1 ↑ | AbsRel ↓ | RMSE ↓ | d1_si ↑ | d1_ssi ↑ | d1_lsl ↑ |",
                "|---|---|---|---|---|---|---|---|---|---|"]
        for d, tag, model, n, m, bf in sorted(rows, key=lambda r: -float(r[4].get("d1", 0))):
            out.append(f"| {d.replace('results_', '')} | {tag} | {params(model)} | {n} | {f(m.get('d1'), True)} | "
                       f"{f(m.get('arel'))} | {f(m.get('rmse'))} | {f(m.get('d1_si'), True)} | {f(m.get('d1_ssi'), True)} | "
                       f"{f(m.get('d1_lsl'), True)} |")
        out.append("")
    txt = "\n".join(out)
    os.makedirs(os.path.join(ROOT, "docs"), exist_ok=True)
    open(os.path.join(ROOT, "docs", "ALL_RESULTS.md"), "w", encoding="utf-8").write(txt + "\n")
    print(txt)


if __name__ == "__main__":
    main()
